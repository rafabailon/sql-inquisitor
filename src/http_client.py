"""HTTP transport with throttling, retries, body limits and WAF observation."""

from __future__ import annotations

import logging
import random
import re
import threading
import time
from typing import Any
from urllib.parse import urlsplit

import requests

from config import ScanConfig
from errors import RequestBudgetExceeded
from models import HttpResponse, RequestSpec, ScanStats

BLOCKED_STATUSES = {403, 406, 429, 503}
RETRY_STATUSES = {502, 504}
MAX_RETRY_AFTER = 30.0

_WAF_HEADER_RULES: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("Cloudflare", ("cf-ray", "cf-cache-status")),
    ("Sucuri", ("x-sucuri-id", "x-sucuri-cache")),
    ("Imperva/Incapsula", ("x-iinfo", "x-incap-session-id")),
    ("Akamai", ("x-akamai-transformed", "akamai-grn")),
    ("AWS WAF", ("x-amzn-waf-action",)),
    ("Azure WAF", ("x-azure-ref", "x-fd-int-roxy-purgeid")),
)

_WAF_BODY_RULES: tuple[tuple[str, str], ...] = (
    ("Cloudflare", r"Attention Required!\s*\|\s*Cloudflare|cf-error-details|Ray ID:"),
    ("Sucuri", r"Sucuri WebSite Firewall|Access Denied - Sucuri Website Firewall"),
    (
        "Imperva/Incapsula",
        r"Incapsula incident ID|_Incapsula_Resource|Request unsuccessful\. Incapsula",
    ),
    ("Akamai", r"Reference #\d+\.[0-9a-f]+|Access Denied.{0,80}Akamai"),
    ("AWS WAF", r"Request blocked.{0,120}AWS WAF|The request could not be satisfied"),
    ("F5 BIG-IP ASM", r"The requested URL was rejected.{0,160}(?:BIG-IP|F5)|support ID"),
    ("ModSecurity", r"ModSecurity|This error was generated by Mod_Security"),
    ("Wordfence", r"Wordfence|Your access to this site has been limited"),
    ("Barracuda", r"Barracuda Networks|Barracuda Web Application Firewall"),
    ("Azure WAF", r"Azure Web Application Firewall|The request was blocked by Azure"),
)


def detect_waf(status_code: int, headers: dict[str, str], body: str) -> str | None:
    """Return the name of a recognizable WAF or blocking layer, if any."""
    lowered = {name.lower(): value for name, value in headers.items()}
    for name, header_names in _WAF_HEADER_RULES:
        if any(header in lowered for header in header_names):
            if name == "Azure WAF" and status_code not in BLOCKED_STATUSES:
                continue
            return name
    sample = body[:200_000] if body else ""
    for name, pattern in _WAF_BODY_RULES:
        if sample and re.search(pattern, sample, re.IGNORECASE):
            return name
    if status_code == 406 and "not acceptable" in sample.lower():
        return "Generic WAF"
    return None


def _retry_after_seconds(headers: dict[str, str]) -> float | None:
    raw = headers.get("retry-after")
    if not raw:
        return None
    try:
        return min(max(float(raw.strip()), 0.0), MAX_RETRY_AFTER)
    except ValueError:
        return 1.0


def _decode_body(content: bytes, content_type: str) -> str:
    match = re.search(r"charset=([\w.\-]+)", content_type, re.IGNORECASE)
    candidates: list[str] = []
    if match:
        candidates.append(match.group(1))
    candidates.extend(["utf-8", "latin-1"])
    for encoding in candidates:
        try:
            return content.decode(encoding)
        except (LookupError, UnicodeDecodeError):
            continue
    return content.decode("utf-8", errors="replace")


class HttpClient:
    """Small, deterministic wrapper around ``requests``.

    The client serializes requests with a minimum interval, respects a request budget, retries
    only safe transport failures, and records WAF observations without trying to defeat them
    automatically.
    """

    def __init__(
        self,
        config: ScanConfig,
        stats: ScanStats | None = None,
        logger: logging.Logger | None = None,
        session: requests.Session | None = None,
    ) -> None:
        self.config = config
        self.stats = stats or ScanStats()
        self.logger = logger or logging.getLogger("sql_inquisitor.http")
        self._session = session or requests.Session()
        self._owns_session = session is None
        self._session.trust_env = config.trust_env
        self._session.headers.update(
            {
                "User-Agent": config.user_agent,
                "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8",
                "Accept-Language": "en-US,en;q=0.8",
            }
        )
        if config.headers:
            self._session.headers.update(config.headers)
        if config.cookies:
            self._session.cookies.update(config.cookies)
        if config.proxy:
            self._session.proxies.update({"http": config.proxy, "https": config.proxy})
        self._lock = threading.Lock()
        self._last_started = 0.0
        self._penalty_until = 0.0

    def _throttle(self) -> None:
        while True:
            with self._lock:
                now = time.monotonic()
                ready_at = max(self._last_started + self.config.delay, self._penalty_until)
                if now >= ready_at:
                    self._last_started = now
                    return
                wait_for = ready_at - now
            if wait_for > 0:
                time.sleep(wait_for)

    def _apply_penalty(self, response_headers: dict[str, str]) -> None:
        seconds = _retry_after_seconds(response_headers)
        if seconds is None:
            seconds = min(max(1.0, self.config.delay * 2), 10.0)
        with self._lock:
            self._penalty_until = max(self._penalty_until, time.monotonic() + seconds)

    def _read_body(self, response: requests.Response) -> tuple[str, bool]:
        content = bytearray()
        truncated = False
        for chunk in response.iter_content(chunk_size=16_384):
            if not chunk:
                continue
            remaining = self.config.max_body_bytes - len(content)
            if remaining <= 0:
                truncated = True
                break
            if len(chunk) > remaining:
                content.extend(chunk[:remaining])
                truncated = True
                break
            content.extend(chunk)
        return _decode_body(bytes(content), response.headers.get("content-type", "")), truncated

    def request(
        self,
        method: str,
        url: str,
        params: Any = None,
        data: Any = None,
        files: Any = None,
        headers: dict[str, str] | None = None,
        allow_redirects: bool | None = None,
    ) -> HttpResponse:
        if self.stats.requests >= self.config.max_requests:
            raise RequestBudgetExceeded(
                f"request budget of {self.config.max_requests} requests exhausted"
            )
        method = method.upper()
        attempt = 0
        while True:
            self._throttle()
            if self.stats.requests >= self.config.max_requests:
                raise RequestBudgetExceeded(
                    f"request budget of {self.config.max_requests} requests exhausted"
                )
            self.stats.requests += 1
            started = time.monotonic()
            try:
                response = self._session.request(
                    method=method,
                    url=url,
                    params=params,
                    data=data,
                    files=files,
                    headers=headers or None,
                    timeout=(self.config.connect_timeout, self.config.timeout),
                    allow_redirects=(
                        self.config.follow_redirects if allow_redirects is None else allow_redirects
                    ),
                    verify=self.config.verify_tls,
                )
                body, truncated = self._read_body(response)
                elapsed = time.monotonic() - started
                response_headers = {name.lower(): value for name, value in response.headers.items()}
                waf = detect_waf(response.status_code, response_headers, body)
                blocked = response.status_code in BLOCKED_STATUSES
                if blocked:
                    self.stats.blocked_requests += 1
                    if response.status_code in {429, 503}:
                        self._apply_penalty(response_headers)
                if waf and waf not in self.stats.waf_observed:
                    self.stats.waf_observed.append(waf)
                    self.logger.warning("WAF or filtering layer observed: %s", waf)
                record = HttpResponse(
                    url=response.url,
                    method=method,
                    status_code=response.status_code,
                    body=body,
                    headers=response_headers,
                    elapsed=elapsed,
                    blocked=blocked,
                    waf=waf,
                    truncated=truncated,
                )
                response.close()
                if (
                    response.status_code in RETRY_STATUSES
                    and attempt < self.config.max_retries
                    and method in {"GET", "HEAD"}
                ):
                    self._backoff(attempt)
                    attempt += 1
                    continue
                if truncated:
                    self.logger.debug(
                        "response body truncated at %s bytes", self.config.max_body_bytes
                    )
                return record
            except requests.RequestException as exc:
                elapsed = time.monotonic() - started
                self.stats.errors += 1
                message = str(exc).strip().replace("\n", " ")[:500]
                if attempt < self.config.max_retries and method in {"GET", "HEAD"}:
                    self.logger.debug("transport error on attempt %s: %s", attempt + 1, message)
                    self._backoff(attempt)
                    attempt += 1
                    continue
                self.logger.debug("request failed: %s %s: %s", method, url, message)
                return HttpResponse(
                    url=url,
                    method=method,
                    status_code=0,
                    body="",
                    headers={},
                    elapsed=elapsed,
                    error=message or exc.__class__.__name__,
                )

    @staticmethod
    def _backoff(attempt: int) -> None:
        time.sleep(min(0.5 * (2**attempt), 5.0) + random.uniform(0.0, 0.2))

    def request_spec(
        self, spec: RequestSpec, headers: dict[str, str] | None = None
    ) -> HttpResponse:
        return self.request(headers=headers, **spec.as_kwargs())

    def close(self) -> None:
        if self._owns_session:
            self._session.close()

    def __enter__(self) -> HttpClient:
        return self

    def __exit__(self, exc_type, exc, traceback) -> None:
        self.close()


def host_of(url: str) -> str:
    return (urlsplit(url).hostname or "").lower()

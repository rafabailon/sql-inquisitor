"""Small, safe payload transformations used to evade naive signature filters.

The transformations deliberately stay within the semantics of the generated payloads. They do
not encode the request a second time, because the HTTP client already performs URL encoding.
Only SQL keywords are rewritten, so string literals generated by the payload module are left
untouched.
"""

from __future__ import annotations

import random
import re
from collections.abc import Iterable

TAMPER_STRATEGIES: dict[str, str] = {
    "randomcase": "Randomize the case of SQL tokens outside quoted strings.",
    "spaces": "Replace spaces with inline SQL comments outside the trailing comment.",
    "versioned": "Wrap common MySQL keywords in versioned inline comments.",
}

_KEYWORDS = re.compile(
    r"\b(SELECT|UNION|AND|OR|SLEEP|WAITFOR|DELAY|FROM|WHERE|ORDER|BY|NULL|LIMIT)\b",
    re.IGNORECASE,
)


def _random_case(payload: str) -> str:
    generator = random.SystemRandom()

    def replace(match: re.Match[str]) -> str:
        token = match.group(0)
        return "".join(
            character.upper() if generator.random() < 0.5 else character.lower()
            for character in token
        )

    return _KEYWORDS.sub(replace, payload)


def _split_trailing_comment(payload: str) -> tuple[str, str]:
    dash = payload.rfind("--")
    hash_at = payload.rfind("#")
    comment_at = max(dash, hash_at)
    if comment_at < 0:
        return payload, ""
    return payload[:comment_at], payload[comment_at:]


def _space_to_comment(payload: str) -> str:
    prefix, comment = _split_trailing_comment(payload)
    transformed = re.sub(r"\s+", "/**/", prefix.strip())
    return transformed + ((" " + comment.lstrip()) if comment else "")


def _versioned_comments(payload: str) -> str:
    def replace(match: re.Match[str]) -> str:
        return f"/*!50000{match.group(0)}*/"

    prefix, comment = _split_trailing_comment(payload)
    transformed = _KEYWORDS.sub(replace, prefix)
    return transformed + ((" " + comment.lstrip()) if comment else "")


_TRANSFORMS = {
    "randomcase": _random_case,
    "spaces": _space_to_comment,
    "versioned": _versioned_comments,
}


def apply_tampers(payload: str, strategies: Iterable[str]) -> str:
    """Apply the named strategies in order, ignoring unknown names."""
    transformed = payload
    for strategy in strategies:
        transform = _TRANSFORMS.get(strategy)
        if transform is not None:
            transformed = transform(transformed)
    return transformed

def test_request_budget_is_enforced(config_factory, lab):
    config = config_factory(max_requests=1)
    client = HttpClient(config)
    try:
        first = client.request("GET", lab.base_url + "/clean?q=test")
        assert first.status_code == 200
        with pytest.raises(RequestBudgetExceeded):
            client.request("GET", lab.base_url + "/clean?q=test")
    finally:
        client.close()


def test_transport_error_is_returned_not_raised(config_factory):
    config = config_factory(
        target="http://127.0.0.1:1/",
        timeout=1.0,
        connect_timeout=0.5,
        time_delay=0.2,
        max_retries=0,
    )
    stats = ScanStats()
    client = HttpClient(config, stats=stats)
    try:
        response = client.request("GET", "http://127.0.0.1:1/")
    finally:
        client.close()
    assert response.status_code == 0
    assert response.error
    assert stats.errors == 1
    assert not response.ok


def test_throttle_enforces_minimum_interval(config_factory, lab):
    config = config_factory(delay=0.05)
    client = HttpClient(config)
    try:
        client.request("GET", lab.base_url + "/clean?q=test")
        started = time.monotonic()
        client.request("GET", lab.base_url + "/clean?q=test")
        elapsed = time.monotonic() - started
    finally:
        client.close()
    assert elapsed >= 0.04


def test_client_context_manager_closes_session(config_factory):
    config = config_factory()
    with HttpClient(config) as client:
        assert client._session is not None
    assert client._session is not None

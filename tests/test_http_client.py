"""HTTP client, WAF detection, retry and budget tests."""

from __future__ import annotations

import time

import pytest

from errors import RequestBudgetExceeded
from http_client import (
    HttpClient,
    _decode_body,
    _retry_after_seconds,
    detect_waf,
    host_of,
)
from models import ScanStats


def test_detect_waf_from_headers():
    assert detect_waf(403, {"cf-ray": "abc"}, "") == "Cloudflare"
    assert detect_waf(403, {"x-sucuri-id": "1"}, "") == "Sucuri"
    assert detect_waf(403, {"x-iinfo": "1"}, "") == "Imperva/Incapsula"
    assert detect_waf(403, {"x-akamai-transformed": "1"}, "") == "Akamai"
    assert detect_waf(403, {"x-amzn-waf-action": "block"}, "") == "AWS WAF"


def test_detect_waf_from_body():
    assert detect_waf(403, {}, "Attention Required! | Cloudflare") == "Cloudflare"
    assert detect_waf(200, {}, "This error was generated by Mod_Security") == "ModSecurity"
    assert detect_waf(403, {}, "Request blocked by AWS WAF") == "AWS WAF"
    assert detect_waf(406, {}, "Not Acceptable") == "Generic WAF"


def test_detect_waf_returns_none_for_normal_response():
    assert detect_waf(200, {"server": "nginx"}, "<html>hello</html>") is None
    assert detect_waf(404, {}, "not found") is None


def test_azure_waf_header_requires_blocking_status():
    assert detect_waf(200, {"x-azure-ref": "abc"}, "") is None
    assert detect_waf(403, {"x-azure-ref": "abc"}, "") == "Azure WAF"


def test_retry_after_parsing():
    assert _retry_after_seconds({"retry-after": "2"}) == 2.0
    assert _retry_after_seconds({"retry-after": "-3"}) == 0.0
    assert _retry_after_seconds({"retry-after": "999"}) == 30.0
    assert _retry_after_seconds({"retry-after": "soon"}) == 1.0
    assert _retry_after_seconds({}) is None


def test_body_decoding_prefers_declared_charset():
    text = "caf\u00e9"
    content = text.encode("latin-1")
    assert _decode_body(content, "text/html; charset=latin-1") == text
    assert _decode_body(b"hello", "text/plain") == "hello"


def test_host_of():
    assert host_of("https://Example.TEST/path") == "example.test"
    assert host_of("http://127.0.0.1:8080/") == "127.0.0.1"


def test_basic_request_records_metadata(config_factory, lab):
    config = config_factory()
    stats = ScanStats()
    client = HttpClient(config, stats=stats)
    try:
        response = client.request("GET", lab.base_url + "/clean?q=test")
    finally:
        client.close()
    assert response.ok
    assert response.status_code == 200
    assert response.error is None
    assert "Clean search" in response.body
    assert response.headers["x-lab"] == "sql-inquisitor"
    assert response.elapsed >= 0
    assert stats.requests == 1
    assert stats.errors == 0


def test_post_request_sends_form_data(config_factory, lab):
    config = config_factory(path="/search")
    client = HttpClient(config)
    try:
        response = client.request(
            "POST",
            lab.base_url + "/search",
            data={"q": "test"},
            headers={"Content-Type": "application/x-www-form-urlencoded"},
        )
    finally:
        client.close()
    assert response.status_code == 200
    assert "Results for: test" in response.body


